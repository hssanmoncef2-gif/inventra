const I18nContext = createContext();

export function I18nProvider({ children }) {
  const [lang, setLang] = useState(() => localStorage.getItem('inventra-lang') || 'en');

  useEffect(() => {
    localStorage.setItem('inventra-lang', lang);
    document.documentElement.dir = translations[lang].dir;
    document.documentElement.lang = lang;
  }, [lang]);

  const t = (key) => translations[lang][key] || key;

  // Format currency as Tunisian Dinar
  const fmtCur = (n) => {
    const num = Number(n) || 0;
    const formatted = new Intl.NumberFormat(lang === 'ar' ? 'ar-TN' : lang === 'fr' ? 'fr-TN' : 'en-TN', {
      minimumFractionDigits: 3,
      maximumFractionDigits: 3,
    }).format(num);
    return lang === 'ar' ? `${formatted} د.ت` : `${formatted} TND`;
  };

  const fmt = (n) => new Intl.NumberFormat(lang === 'ar' ? 'ar-TN' : 'en').format(Math.round(n || 0));

  return (
    <I18nContext.Provider value={{ lang, setLang, t, fmtCur, fmt }}>
      {children}
    </I18nContext.Provider>
  );
}

export const useI18n = () => useContext(I18nContext);
